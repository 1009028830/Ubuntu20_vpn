import argparse
import json
import os
import secrets
from pathlib import Path
from typing import Optional
from urllib.parse import parse_qs, unquote, urlparse


DEFAULT_CONFIG_PATH = "/etc/mihomo/config.yaml"
DEFAULT_SERVICE_PATH = "/etc/systemd/system/mihomo.service"


def handle_clash_command(args: argparse.Namespace) -> int:
    if args.clash_command == "ui":
        from .mihomo_ui import serve_ui

        serve_ui(
            host=args.host,
            port=args.port,
            config_path=args.config,
            controller=args.controller,
            secret=args.secret,
            open_browser=args.open,
        )
        return 0

    if args.clash_command == "render-config":
        subscription_url = read_subscription_url(args.subscription_url, args.subscription_file)
        config = render_config(
            subscription_url=subscription_url,
            mixed_port=args.mixed_port,
            controller=args.external_controller,
            controller_secret=args.controller_secret,
            mode=args.mode,
            allow_lan=args.allow_lan,
            tun_enabled=not args.no_tun,
            dns_enabled=not args.no_dns,
        )
        write_text_or_stdout(config, args.output)
        return 0

    if args.clash_command == "render-service":
        service = render_systemd_service(args.config_dir, args.binary)
        write_text_or_stdout(service, args.output)
        return 0

    if args.clash_command == "init":
        subscription_url = read_subscription_url(args.subscription_url, args.subscription_file)
        config_path = Path(args.config)
        service_path = Path(args.service)
        config = render_config(
            subscription_url=subscription_url,
            mixed_port=args.mixed_port,
            controller=args.external_controller,
            controller_secret=args.controller_secret,
            mode=args.mode,
            allow_lan=args.allow_lan,
            tun_enabled=not args.no_tun,
            dns_enabled=not args.no_dns,
        )
        service = render_systemd_service(str(config_path.parent), args.binary)

        config_path.parent.mkdir(parents=True, exist_ok=True)
        service_path.parent.mkdir(parents=True, exist_ok=True)
        providers_dir = config_path.parent / "providers"
        providers_dir.mkdir(parents=True, exist_ok=True)

        config_path.write_text(config, encoding="utf-8")
        service_path.write_text(service, encoding="utf-8")
        os.chmod(config_path, 0o600)
        os.chmod(service_path, 0o644)

        print(f"wrote config: {config_path}")
        print(f"wrote service: {service_path}")
        print("next: sudo systemctl daemon-reload && sudo systemctl enable --now mihomo")
        return 0

    raise ValueError("missing clash subcommand")


def read_subscription_url(subscription_url: Optional[str], subscription_file: Optional[str]) -> str:
    if subscription_url and subscription_file:
        raise ValueError("use either --subscription-url or --subscription-file, not both")

    value = subscription_url
    if subscription_file:
        value = Path(subscription_file).read_text(encoding="utf-8").strip()
    if not value:
        value = os.environ.get("U20VPN_CLASH_SUBSCRIPTION", "").strip()

    if not value:
        raise ValueError("missing subscription URL; use --subscription-url, --subscription-file, or U20VPN_CLASH_SUBSCRIPTION")

    return normalize_subscription_url(value)


def normalize_subscription_url(value: str) -> str:
    value = value.strip()
    parsed = urlparse(value)

    if parsed.scheme in {"http", "https"}:
        return value

    if parsed.scheme == "clash":
        query = parse_qs(parsed.query)
        candidates = query.get("url") or query.get("subscribe") or query.get("sub")
        if candidates:
            return normalize_subscription_url(unquote(candidates[0]))

    supported_node_prefixes = ("ss://", "ssr://", "vmess://", "vless://", "trojan://", "hysteria2://", "tuic://")
    if value.startswith(supported_node_prefixes):
        raise ValueError("this helper expects a Clash subscription URL, not a single node URI")

    raise ValueError("subscription URL must start with http://, https://, or clash://install-config?url=...")


def render_config(
    subscription_url: str,
    mixed_port: int = 7890,
    controller: str = "127.0.0.1:9090",
    controller_secret: Optional[str] = None,
    mode: str = "rule",
    allow_lan: bool = False,
    tun_enabled: bool = True,
    dns_enabled: bool = True,
) -> str:
    if mode not in {"rule", "global", "direct"}:
        raise ValueError("mode must be rule, global, or direct")
    if controller_secret is None:
        controller_secret = secrets.token_urlsafe(24)

    lines = [
        "# Generated by u20vpn. Keep this file private because it contains your subscription URL.",
        f"mixed-port: {int(mixed_port)}",
        f"allow-lan: {yaml_bool(allow_lan)}",
        'bind-address: "127.0.0.1"' if not allow_lan else 'bind-address: "*"',
        f"mode: {mode}",
        "log-level: info",
        "ipv6: false",
        f"external-controller: {yaml_str(controller)}",
        f"secret: {yaml_str(controller_secret)}",
        "",
        "profile:",
        "  store-selected: true",
        "  store-fake-ip: true",
        "",
    ]

    if tun_enabled:
        lines.extend(
            [
                "tun:",
                "  enable: true",
                "  stack: system",
                "  device: mihomo",
                "  auto-route: true",
                "  auto-detect-interface: true",
                "  strict-route: false",
                "  dns-hijack:",
                '    - "any:53"',
                '    - "tcp://any:53"',
                "",
            ]
        )
    else:
        lines.extend(["tun:", "  enable: false", ""])

    if dns_enabled:
        lines.extend(
            [
                "dns:",
                "  enable: true",
                '  listen: "127.0.0.1:1053"',
                "  ipv6: false",
                "  enhanced-mode: fake-ip",
                '  fake-ip-range: "198.18.0.1/16"',
                "  default-nameserver:",
                "    - 223.5.5.5",
                "    - 119.29.29.29",
                "  nameserver:",
                "    - https://dns.alidns.com/dns-query",
                "    - https://doh.pub/dns-query",
                "",
            ]
        )
    else:
        lines.extend(["dns:", "  enable: false", ""])

    lines.extend(
        [
            "proxy-providers:",
            "  subscription:",
            "    type: http",
            f"    url: {yaml_str(subscription_url)}",
            "    interval: 3600",
            "    path: ./providers/subscription.yaml",
            "    health-check:",
            "      enable: true",
            "      lazy: true",
            "      interval: 600",
            "      url: https://www.gstatic.com/generate_204",
            "",
            "proxy-groups:",
            "  - name: PROXY",
            "    type: select",
            "    use:",
            "      - subscription",
            "    proxies:",
            "      - AUTO",
            "      - DIRECT",
            "  - name: AUTO",
            "    type: url-test",
            "    use:",
            "      - subscription",
            "    url: https://www.gstatic.com/generate_204",
            "    interval: 300",
            "",
            "rules:",
            "  - IP-CIDR,127.0.0.0/8,DIRECT,no-resolve",
            "  - IP-CIDR,10.0.0.0/8,DIRECT,no-resolve",
            "  - IP-CIDR,172.16.0.0/12,DIRECT,no-resolve",
            "  - IP-CIDR,192.168.0.0/16,DIRECT,no-resolve",
            "  - IP-CIDR,169.254.0.0/16,DIRECT,no-resolve",
            "  - MATCH,PROXY",
            "",
        ]
    )
    return "\n".join(lines)


def render_systemd_service(config_dir: str = "/etc/mihomo", binary: str = "/usr/local/bin/mihomo") -> str:
    return "\n".join(
        [
            "[Unit]",
            "Description=mihomo proxy service",
            "After=network-online.target",
            "Wants=network-online.target",
            "",
            "[Service]",
            "Type=simple",
            f"ExecStart={binary} -d {config_dir}",
            "Restart=on-failure",
            "RestartSec=5",
            "LimitNOFILE=1000000",
            "AmbientCapabilities=CAP_NET_ADMIN CAP_NET_BIND_SERVICE CAP_NET_RAW",
            "CapabilityBoundingSet=CAP_NET_ADMIN CAP_NET_BIND_SERVICE CAP_NET_RAW",
            "NoNewPrivileges=false",
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        ]
    )


def write_text_or_stdout(text: str, output: Optional[str]) -> None:
    if output:
        path = Path(output)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        if path.name == "config.yaml":
            os.chmod(path, 0o600)
        print(f"wrote: {path}")
    else:
        print(text, end="")


def yaml_str(value: str) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def yaml_bool(value: bool) -> str:
    return "true" if value else "false"
